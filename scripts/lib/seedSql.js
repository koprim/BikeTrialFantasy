const BALANCE_VERSION = 1;

function sqlLiteral(value) {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number' && !Number.isFinite(value))
    throw new Error(`Cannot seed a non-finite number: ${value}`);
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  return `'${String(value).replace(/'/g, "''")}'`;
}

// Guards NOT NULL columns so a bad seed fails here, naming the table and id, not in Postgres.
function required(row, key, table) {
  const value = row[key];
  if (value === null || value === undefined) throw new Error(`Seed ${table} ${row.id}: missing required "${key}"`);
  return value;
}

const jsonLiteral = (value) => `${sqlLiteral(JSON.stringify(value))}::jsonb`;
const textArray = (values) => `array[${values.map(sqlLiteral).join(', ')}]::text[]`;

function insert(table, columns, rows) {
  if (!rows.length) return '';
  const values = rows.map((row) => `  (${row.join(', ')})`).join(',\n');
  return `insert into public.${table} (${columns.join(', ')}) values\n${values};\n`;
}

// { fr: 'Gap', en: 'Gap' }: every language with a non-empty text.
function localized(texts, read) {
  const out = {};
  Object.entries(texts).forEach(([code, game]) => {
    const value = read(game || {});
    if (typeof value === 'string' && value !== '') out[code] = value;
  });
  return out;
}

function requiredName(texts, read, table, id) {
  const names = localized(texts, read);
  if (!Object.keys(names).length) throw new Error(`Seed ${table} ${id}: missing required "name"`);
  return jsonLiteral(names);
}

const seasonRow = (texts) => (season) => {
  const id = required(season, 'id', 'seasons');
  return [sqlLiteral(id), requiredName(texts, (game) => game.seasons?.[id]?.name, 'seasons', id)];
};
const riderRow = (rider) => [
  sqlLiteral(required(rider, 'id', 'riders')),
  sqlLiteral(required(rider, 'name', 'riders')),
  sqlLiteral(required(rider, 'country', 'riders')),
  sqlLiteral(required(rider, 'category', 'riders')),
  sqlLiteral(rider.brand),
  sqlLiteral(rider.cote),
  sqlLiteral(rider.uciRank),
  sqlLiteral(rider.active !== false),
];
const competitionRow = (texts, season) => (event) => {
  const id = required(event, 'id', 'competitions');
  return [
    sqlLiteral(id),
    sqlLiteral(season.id),
    requiredName(texts, (game) => game.events?.[id]?.name, 'competitions', id),
    sqlLiteral(event.venue),
    sqlLiteral(event.country),
    sqlLiteral(event.round),
    sqlLiteral(required(event, 'dateFrom', 'competitions')),
    sqlLiteral(event.dateTo || event.dateFrom),
    sqlLiteral(event.referee),
  ];
};
const localizedEffects = (texts, card) =>
  required(card, 'effects', 'cards').map(({ description, ...effect }, index) => ({
    ...effect,
    description: localized(texts, (game) => game.cards?.[card.id]?.effects?.[index]),
  }));
const cardRow = (texts) => (card) => {
  const id = required(card, 'id', 'cards');
  return [
    sqlLiteral(id),
    sqlLiteral(required(card, 'type', 'cards')),
    sqlLiteral(required(card, 'edition', 'cards')),
    requiredName(texts, (game) => game.cards?.[id]?.name, 'cards', id),
    sqlLiteral(card.subject),
    textArray(required(card, 'rarities', 'cards')),
    jsonLiteral(localizedEffects(texts, card)),
  ];
};

/**
 * Texts come only from `texts` ({ <code>: game.json content }); name / description in the seed are ignored.
 */
function buildSeedSql({ seasons, riders, cards, balance, texts }) {
  return [
    '-- GENERATED by scripts/build-sql-seed.js from src/data/seed and src/i18n/locales. Do not edit.\n',
    insert('seasons', ['id', 'name'], seasons.map(seasonRow(texts))),
    insert('riders', ['id', 'name', 'nation', 'category', 'brand', 'cote', 'uci_rank', 'active'], riders.map(riderRow)),
    insert(
      'competitions',
      ['id', 'season_id', 'name', 'venue', 'country', 'round', 'date_from', 'date_to', 'referee'],
      seasons.flatMap((season) => season.events.map(competitionRow(texts, season))),
    ),
    insert('cards', ['id', 'type', 'edition', 'name', 'subject_id', 'rarities', 'effects'], cards.map(cardRow(texts))),
    insert('balance', ['version', 'data'], [[sqlLiteral(BALANCE_VERSION), jsonLiteral(balance)]]),
  ].join('\n');
}

module.exports = { buildSeedSql, sqlLiteral, BALANCE_VERSION };
